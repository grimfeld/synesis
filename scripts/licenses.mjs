#!/usr/bin/env node
// Third-party notices: every npm package the UI ships and every crate the
// app links, with its licence and the licence files it carries, written to
// public/third-party-licenses.txt, which Settings → About opens. MIT, BSD
// and Apache all ask that their notice travel with the program.
//
//   npm run licenses            regenerate the file
//   npm run licenses -- --check fail if the file is out of date (CI)
//
// Crates come from `cargo metadata` (normal dependencies of the shell, every
// platform at once); npm packages from package-lock.json without the dev
// ones. Identical licence texts are written once and referred to after.
import { execSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "public", "third-party-licenses.txt");
const check = process.argv.includes("--check");

const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)([-._].*)?$/i;
const licenseFiles = (dir) =>
  existsSync(dir)
    ? readdirSync(dir, { withFileTypes: true })
        .filter((e) => e.isFile() && LICENSE_FILE.test(e.name))
        .map((e) => e.name)
        .sort()
    : [];

/** @type {{ name: string, version: string, license: string, url: string, dir: string, kind: string }[]} */
const packages = [];

// --- Crates -----------------------------------------------------------------
const meta = JSON.parse(
  execSync("cargo metadata --format-version 1 --locked", { cwd: root, encoding: "utf8", maxBuffer: 256 << 20 }),
);
const byId = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const own = new Set(meta.workspace_members);
const start = meta.packages.find((p) => p.name === "synesis" && own.has(p.id));
if (!start) throw new Error("no `synesis` package in the workspace");
const seen = new Set();
const queue = [start.id];
while (queue.length) {
  const id = queue.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const d of nodes.get(id)?.deps ?? []) {
    // Build scripts and dev dependencies are not part of the program.
    if (d.dep_kinds.some((k) => k.kind === null)) queue.push(d.pkg);
  }
}
for (const id of seen) {
  if (own.has(id)) continue;
  const p = byId.get(id);
  packages.push({
    name: p.name,
    version: p.version,
    license: p.license ?? (p.license_file ? "see file" : "unknown"),
    url: p.repository ?? p.homepage ?? `https://crates.io/crates/${p.name}`,
    dir: dirname(p.manifest_path),
    kind: "crate",
  });
}

// --- npm packages -----------------------------------------------------------
const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
for (const [path, p] of Object.entries(lock.packages)) {
  // Platform-specific binaries (esbuild, rollup, the Tauri CLI) are build
  // tools, and installed only on their own platform.
  if (!path || p.dev || p.devOptional || p.link || p.os || p.cpu) continue;
  const dir = join(root, path);
  const pj = existsSync(join(dir, "package.json")) ? JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) : {};
  const name = pj.name ?? path.replace(/^.*node_modules\//, "");
  const repo = typeof pj.repository === "string" ? pj.repository : pj.repository?.url;
  packages.push({
    name,
    version: p.version ?? pj.version ?? "",
    license: p.license ?? (typeof pj.license === "string" ? pj.license : pj.license?.type) ?? "unknown",
    url: (repo ?? pj.homepage ?? `https://www.npmjs.com/package/${name}`).replace(/^git\+/, ""),
    dir,
    kind: "npm",
  });
}

// --- Bundled fonts ------------------------------------------------------------
const fonts = join(root, "src", "assets", "fonts");
if (existsSync(fonts)) {
  for (const d of readdirSync(fonts, { withFileTypes: true }).filter((e) => e.isDirectory())) {
    packages.push({ name: d.name, version: "", license: "see file", url: "", dir: join(fonts, d.name), kind: "font" });
  }
}

// --- Write --------------------------------------------------------------------
const order = { font: 0, npm: 1, crate: 2 };
packages.sort((a, b) => order[a.kind] - order[b.kind] || a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const texts = new Map(); // hash -> "name version / file" where first written
const parts = [
  "Synesis is free software under the GNU AGPL-3.0 (see LICENSE).",
  "It is built with the following third-party software, each under its own licence.",
  "Generated by scripts/licenses.mjs.",
  "",
];
const missing = [];
for (const p of packages) {
  const title = `${p.name}${p.version ? ` ${p.version}` : ""}`;
  parts.push("=".repeat(78), `${title} (${p.kind})`, `Licence: ${p.license}`);
  if (p.url) parts.push(`Source: ${p.url}`);
  const files = licenseFiles(p.dir);
  if (files.length === 0) missing.push(title);
  for (const f of files) {
    const text = readFileSync(join(p.dir, f), "utf8").replace(/\r\n/g, "\n").trim();
    const h = createHash("sha256").update(text).digest("hex");
    if (texts.has(h)) {
      parts.push("", `${f}: same text as ${texts.get(h)}.`);
    } else {
      texts.set(h, `${title} / ${f}`);
      parts.push("", `--- ${f} ---`, text);
    }
  }
  parts.push("");
}
const body = parts.join("\n") + "\n";

if (check) {
  const current = existsSync(out) ? readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== body) {
    console.error("public/third-party-licenses.txt is out of date: run `npm run licenses` and commit it.");
    process.exit(1);
  }
  console.log(`third-party notices up to date (${packages.length} packages)`);
} else {
  writeFileSync(out, body);
  console.log(
    `wrote ${packages.length} packages, ${texts.size} distinct licence texts, ${(body.length / 1024).toFixed(0)} KB` +
      (missing.length ? `; ${missing.length} carry no licence file (licence named only)` : ""),
  );
}
